local map = {}
local chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
for i = 1, 64 do map[chars:sub(i, i)] = i - 1 end
local function decode(s)
	local out, n, bits, nb = {}, 0, 0, 0
	for i = 1, #s do
		local v = map[s:sub(i, i)]
		if v then
			bits = bits * 64 + v; nb = nb + 6
			if nb >= 8 then
				nb = nb - 8
				local div = 2 ^ nb
				local byte = math.floor(bits / div)
				bits = bits - byte * div
				n = n + 1; out[n] = string.char(byte)
				if n % 4000 == 0 then task.wait() end
			end
		end
	end
	return table.concat(out)
end

local ls = loadstring or load
if not ls then say("This executor has no loadstring", true) return end

local function runPart(name, b64)
	local ok, code = pcall(decode, b64)
	if not ok then say(name .. " DECODE ERROR: " .. tostring(code), true) return false end
	local fn, cerr = ls(code, "=" .. name)
	if not fn then say(name .. " COMPILE ERROR: " .. tostring(cerr), true) return false end
	local ok2, err = xpcall(fn, function(e) return tostring(e) .. "\n" .. debug.traceback() end)
	if not ok2 then say(name .. " RUNTIME ERROR: " .. tostring(err):sub(1, 400), true) return false end
	return true
end

