-- Training Hub + Auto Click (all-in-one, ASCII only)
local Players = game:GetService("Players")
local LP = Players.LocalPlayer

local function mount()
	local g = Instance.new("ScreenGui")
	g.Name = "HUBX_LOADER"; g.ResetOnSpawn = false; g.IgnoreGuiInset = true; g.DisplayOrder = 3000
	for _, f in ipairs({
		function() return LP:WaitForChild("PlayerGui", 10) end,
		function() return gethui and gethui() end,
		function() return game:GetService("CoreGui") end,
	}) do
		local ok, p = pcall(f)
		if ok and p then
			pcall(function() local o = p:FindFirstChild("HUBX_LOADER"); if o then o:Destroy() end end)
			if pcall(function() g.Parent = p end) and g.Parent then return g end
		end
	end
	return nil
end
local g = mount()
local lbl
if g then
	lbl = Instance.new("TextLabel", g)
	lbl.Size = UDim2.new(1, 0, 0, 90); lbl.Position = UDim2.new(0, 0, 0, 40)
	lbl.TextColor3 = Color3.new(1, 1, 1); lbl.TextSize = 18; lbl.TextWrapped = true; lbl.ZIndex = 1000
	lbl.BackgroundColor3 = Color3.fromRGB(168, 85, 247)
end
local function say(t, bad)
	print("[HubLoader] " .. tostring(t))
	if lbl then
		lbl.Text = tostring(t)
		lbl.BackgroundColor3 = bad and Color3.fromRGB(200, 40, 40) or Color3.fromRGB(168, 85, 247)
	end
end
say("loader started")

